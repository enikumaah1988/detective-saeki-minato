import test from 'node:test'
import assert from 'node:assert/strict'
import { loadRevision } from './revisionHarness.mjs'
const path = process.env.SAEKI_PLAYWRIGHT_PATH
const url = (process.env.SAEKI_PART1_URL ?? 'http://127.0.0.1:5192/').split('?')[0]
for (const [width, height] of [[1920,1080],[1366,768]]) test(`タイトル画面・新規開始・保存復帰・設定 ${width}`, { skip: !path }, async () => {
  const { chromium } = await import(path), browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width, height } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const api = await loadRevision()
  const state = { ...api.createInitialState(api.scenario), nodeId: 'P1-01-menu' }
  const saved = { version: 1, auto: null, manual: [{ data: api.createSaveData(state), label: 'テスト保存', savedAt: new Date().toISOString(), history: [{ speaker: '佐伯', text: '保存した履歴', nodeId: 'P1-01-menu' }] }] }
  try {
    await page.goto(url)
    await page.waitForFunction(() => { const image = document.querySelector('.title-screen-background'); return image?.complete && image.naturalWidth > 0 })
    assert.equal(await page.locator('.message-window, .history-entry, .story-toolbar').count(), 0)
    const heading = await page.locator('h1').boundingBox()
    assert.ok(heading.x > width*.15 && heading.x + heading.width < width*.85)
    const titleMenu = await page.locator('.title-screen-menu').boundingBox()
    assert.ok(titleMenu.y > height*.48 && titleMenu.y < height*.58 && titleMenu.y + titleMenu.height < height*.78)
    const menuButtons = await page.locator('.title-screen-menu button').all()
    const buttonRects = await Promise.all(menuButtons.map(button => button.boundingBox()))
    assert.ok(buttonRects.every(rect => Math.abs(rect.x - buttonRects[0].x) < 1))
    assert.ok(buttonRects[1].y >= buttonRects[0].y + buttonRects[0].height && buttonRects[2].y >= buttonRects[1].y + buttonRects[1].height)
    assert.equal(await page.locator('.title-screen-menu .ui-icon').count(), 3)
    if (process.env.SAEKI_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.SAEKI_SCREENSHOT_DIR}/title-${width}.png` })
    await page.getByRole('button', { name: 'CONTINUE', exact: true }).click()
    assert.equal(await page.getByRole('dialog').getByRole('button', { name: 'AUTO', exact: true }).isDisabled(), true)
    assert.match(await page.getByRole('dialog').textContent(), /保存データはありません/)
    await page.keyboard.press('Escape')
    await page.waitForFunction(() => !document.querySelector('dialog'))
    await page.waitForFunction(() => document.activeElement?.textContent === 'CONTINUE')
    assert.equal(await page.getByRole('button', { name: 'CONTINUE', exact: true }).evaluate(el => el === document.activeElement), true)
    await page.getByRole('button', { name: 'SETTINGS', exact: true }).click()
    await page.getByRole('slider', { name: 'BGM音量', exact: true }).focus(); await page.keyboard.press('End')
    await page.getByRole('button', { name: /メッセージスピード：一括表示/ }).click()
    await page.getByRole('dialog').getByRole('button', { name: '戻る', exact: true }).click()
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('detective-saeki-minato.audio')).bgm), 100)
    await page.evaluate(value => localStorage.setItem('detective-saeki-minato.slots.v1', JSON.stringify(value)), saved)
    await page.getByRole('button', { name: 'NEW GAME', exact: true }).focus(); await page.keyboard.press('Enter')
    await page.locator('[data-node-id="episode-prologue-1"]').waitFor()
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('detective-saeki-minato.slots.v1'))), saved)
    await page.getByLabel('メニュー', { exact: true }).click()
    assert.equal(await page.getByRole('slider', { name: 'BGM音量', exact: true }).inputValue(), '100')
    await page.getByRole('button', { name: 'RETURN TO TITLE', exact: true }).click()
    assert.match(await page.getByRole('dialog').textContent(), /保存していない進行は失われます/)
    await page.keyboard.press('Enter')
    await page.waitForFunction(() => !document.querySelector('dialog'))
    assert.equal(await page.locator('.story').getAttribute('data-node-id'), 'episode-prologue-1')
    await page.getByRole('button', { name: 'RETURN TO TITLE', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.waitForFunction(() => !document.querySelector('dialog'))
    await page.getByRole('button', { name: 'RETURN TO TITLE', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'タイトルに戻る', exact: true }).click()
    await page.getByRole('region', { name: 'タイトル画面', exact: true }).waitFor()
    assert.equal(await page.locator('[data-node-id]').count(), 0)
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('detective-saeki-minato.slots.v1'))), saved)
    await page.reload()
    await page.getByRole('button', { name: 'CONTINUE', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'SAVE １', exact: true }).click()
    await page.locator('[data-node-id="P1-01-menu"]').waitFor()
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('detective-saeki-minato.slots.v1'))), saved)
    await page.getByLabel('会話履歴を開く', { exact: true }).click()
    assert.match(await page.getByRole('dialog', { name: '会話履歴', exact: true }).textContent(), /保存した履歴/)
    await page.getByRole('dialog').getByRole('button', { name: '閉じる', exact: true }).click()
    await page.getByLabel('メニュー', { exact: true }).click()
    await page.getByRole('button', { name: 'RETURN TO TITLE', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'タイトルに戻る', exact: true }).click()
    await page.getByRole('button', { name: 'NEW GAME', exact: true }).click()
    await page.locator('[data-node-id="episode-prologue-1"]').waitFor()
    await page.getByLabel('会話履歴を開く', { exact: true }).click()
    assert.match(await page.getByRole('dialog').textContent(), /会話履歴はまだありません/)
    await page.reload()
    await page.evaluate(() => localStorage.setItem('detective-saeki-minato.slots.v1', '{broken'))
    await page.getByRole('button', { name: 'CONTINUE', exact: true }).click()
    assert.match(await page.getByRole('status').textContent(), /確認できません/)
    assert.equal(await page.evaluate(() => localStorage.getItem('detective-saeki-minato.slots.v1')), '{broken')
    await page.keyboard.press('Escape')
    await page.evaluate(value => { localStorage.setItem('detective-saeki-minato.slots.v1', JSON.stringify({ version: 1, auto: value.manual[0], manual: [] })) }, saved)
    await page.getByRole('button', { name: 'CONTINUE', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'AUTO', exact: true }).click()
    await page.locator('[data-node-id="P1-01-menu"]').waitFor()
    await page.reload()
    await page.evaluate(value => { localStorage.removeItem('detective-saeki-minato.slots.v1'); localStorage.setItem('detective-saeki-minato.save.v1', JSON.stringify(value)) }, saved.manual[0].data)
    await page.getByRole('button', { name: 'CONTINUE', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'SAVE １', exact: true }).click()
    await page.locator('[data-node-id="P1-01-menu"]').waitFor()
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('detective-saeki-minato.save.v1'))), saved.manual[0].data)
    assert.deepEqual(errors, [])
  } finally { await browser.close() }
})
